export function getInitialLanguage() {
  try {
    const nav = navigator.language || navigator.userLanguage || "de";
    const code = nav.slice(0, 2).toLowerCase();
    if (["de", "en", "fr", "it"].includes(code)) return code;
  } catch {}
  return "de";
}

export function t(lang, key, param) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.de;
  let text = dict[key] || TRANSLATIONS.de[key] || key;
  if (param !== undefined) {
    text = text.replace("%s", param);
  }
  return text;
}